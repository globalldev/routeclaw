#!/usr/bin/env node
// Syncs src/agents/default-system.md → src/agents/default-system-content.ts
// Run after editing the .md file: node scripts/sync-default-system.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const mdPath = join(root, "src", "agents", "default-system.md");
const tsPath = join(root, "src", "agents", "default-system-content.ts");

const content = readFileSync(mdPath, "utf-8");
const serialized = JSON.stringify(content);

const output = `// AUTO-SYNCED from default-system.md — do not edit this file directly.
// To change the default system prompt, edit src/agents/default-system.md
// and run: node scripts/sync-default-system.mjs

export const DEFAULT_SYSTEM_PROMPT: string = ${serialized};
`;

writeFileSync(tsPath, output, "utf-8");
console.log(`synced ${mdPath} → ${tsPath} (${content.length} chars)`);
