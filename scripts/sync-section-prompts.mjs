#!/usr/bin/env node
// Syncs src/agents/section-prompts/*.md → src/agents/section-prompts-content.ts
// Run after editing any section prompt file: node scripts/sync-section-prompts.mjs

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, basename, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "src", "agents", "section-prompts");
const outPath = join(root, "src", "agents", "section-prompts-content.ts");

const files = readdirSync(srcDir).filter((f) => f.endsWith(".md")).sort();

const lines = [
  "// AUTO-SYNCED from src/agents/section-prompts/*.md — do not edit this file directly.",
  "// To change a section prompt, edit the corresponding .md file and run:",
  "//   node scripts/sync-section-prompts.mjs",
  "",
];

const exports = [];
for (const file of files) {
  const content = readFileSync(join(srcDir, file), "utf-8");
  // kebab-name → SCREAMING_SNAKE export name
  const key = basename(file, ".md")
    .toUpperCase()
    .replace(/-/g, "_");
  const exportName = `SECTION_PROMPT_${key}`;
  lines.push(`export const ${exportName}: string = ${JSON.stringify(content)};`);
  exports.push({ file, exportName });
}

lines.push("");
writeFileSync(outPath, lines.join("\n"), "utf-8");

console.log(`synced ${files.length} section prompts → ${outPath}`);
for (const { file, exportName } of exports) {
  console.log(`  ${file} → ${exportName}`);
}
